def _localized_workflow(steps: List[Dict[str, Any]], lang: str) -> List[Dict[str, Any]]:
    out = []
    for s in steps:
        row = dict(s)
        if lang == "zh-HK":
            row["stage"] = STAGE_ZH.get(s.get("stage", ""), s.get("stage", ""))
            step_no = s.get("step")
            if step_no in WORKFLOW_DETAIL_ZH:
                row["detail"] = WORKFLOW_DETAIL_ZH[step_no]
        out.append(row)
    return out


def _localized_records(
    records: List[Dict[str, Any]], detail: Dict[str, Any], lang: str
) -> List[Dict[str, Any]]:
    if lang != "zh-HK":
        return records
    claim = detail.get("contractor_claim_adjudication") or {}
    fair = detail.get("fair_value_calculation") or {}
    photo = (detail.get("cv_module") or {}).get("evidence_chain", {}).get(
        "primary_photo", "IMG_20260728_1045.jpg"
    )
    out = []
    for rec in records:
        row = dict(rec)
        seq = rec.get("seq")
        zh = RECORD_ZH.get(seq, {})
        if zh.get("title"):
            row["title"] = zh["title"]
        if zh.get("source"):
            row["source"] = zh["source"]
        elif seq == 5:
            row["source"] = photo
        if seq == 3 and zh.get("summary") is None:
            fv = float(fair.get("total_fair_value", 18750))
            row["summary"] = f"公平價值 港幣 ${fv:,.0f}（含工地前設 / 公司費及利潤）。"
        elif seq == 4 and zh.get("summary") is None:
            tc = float(claim.get("total_claim", 22510))
            tv = float(claim.get("total_variance", 5920))
            pct = claim.get("inflated_percentage", 26.3)
            row["summary"] = f"申索 港幣 ${tc:,.0f}；差額 港幣 ${tv:,.0f}（{pct}%）。"
        elif zh.get("summary"):
            row["summary"] = zh["summary"]
        out.append(row)
    return out


