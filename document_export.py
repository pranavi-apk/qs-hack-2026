def _fmt_hkd(n: Any, lang: str) -> str:
    try:
        v = float(n)
    except (TypeError, ValueError):
        return str(n)
    if lang == "zh-HK":
        return f"港幣 ${v:,.0f}"
    return f"HK$ {v:,.0f}"


def _normalize_lang(lang: str) -> str:
    if lang in ("zh-HK", "zh", "yue", "cantonese"):
        return "zh-HK"
    if lang.startswith("zh"):
        return "zh-HK"
    return "en"


def _font_css(lang: str, pdf_mode: bool = False) -> str:
    if lang != "zh-HK":
        return ""
    if pdf_mode:
        # xhtml2pdf falls back to Helvetica on bold/strong unless every element names MSung-Light
        return (
            "body, body *, th, td, h1, h2, p, li, footer, div, span, strong, b { "
            "font-family: MSung-Light; "
            "}"
        )
    return (
        'body, th, td, h1, h2, p, li, footer, div { font-family: "PingFang HK", "Microsoft JhengHei", sans-serif; }'
    )


def _register_pdf_cjk_font(lang: str) -> None:
    if lang != "zh-HK":
        return
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.cidfonts import UnicodeCIDFont

    if "MSung-Light" not in pdfmetrics.getRegisteredFontNames():
        pdfmetrics.registerFont(UnicodeCIDFont("MSung-Light"))


def _link_callback(uri: str, rel: str) -> str:
    if uri.startswith("file://"):
        return uri[7:]
    if uri.startswith("file:"):
        return uri[5:]
    return uri


